#!/usr/bin/env python3
"""Generate web/src/lib/db.types.ts from a Postgres database that has the migrations applied.

Emits the same shape as `supabase gen types typescript` (Tables/Views/Functions/Enums with
Row/Insert/Update/Relationships), so the file can later be replaced by the official generator
without touching call sites. Used because the official generator needs Docker images that the
build sandbox cannot pull.

Usage: PGHOST=... PGPORT=... PGUSER=postgres python3 supabase/scripts/gen_types.py <dbname> <out.ts>
"""
import json
import subprocess
import sys

DB = sys.argv[1]
OUT = sys.argv[2]


def q(sql: str):
    res = subprocess.run(
        ["psql", "-X", "-q", "-t", "-A", "-d", DB, "-c", f"select coalesce(json_agg(_q), '[]') from ({sql}) _q"],
        check=True, capture_output=True, text=True,
    )
    return json.loads(res.stdout.strip() or "[]")


enums = q("""
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
  group by t.typname order by t.typname
""")
enum_names = {e["name"] for e in enums}

cols = q("""
  select c.relname as rel, c.relkind as kind, a.attname as col, a.attnum as num,
         format_type(a.atttypid, a.atttypmod) as fmt, ty.typname as typname,
         ety.typname as elemtype, ty.typcategory as cat,
         not a.attnotnull as nullable, a.atthasdef as has_default,
         a.attidentity <> '' as is_identity, a.attgenerated <> '' as is_generated
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  join pg_type ty on ty.oid = a.atttypid
  left join pg_type ety on ety.oid = ty.typelem and ty.typcategory = 'A'
  where c.relkind in ('r', 'v', 'm')
  order by c.relname, a.attnum
""")

fks = q("""
  select con.conname as name, src.relname as rel, tgt.relname as ref,
         array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as columns,
         array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as ref_columns,
         (select count(*) from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('u','p')
            and u.conkey::int[] @> con.conkey::int[] and u.conkey::int[] <@ con.conkey::int[]) > 0 as one_to_one
  from pg_constraint con
  join pg_class src on src.oid = con.conrelid
  join pg_class tgt on tgt.oid = con.confrelid
  join pg_namespace n on n.oid = src.relnamespace and n.nspname = 'public'
  join pg_namespace tn on tn.oid = tgt.relnamespace and tn.nspname = 'public'
  where con.contype = 'f'
  order by src.relname, con.conname
""")

funcs = q("""
  select p.proname as name,
         coalesce(p.proargnames, '{}') as argnames,
         array(select ty.typname from unnest(p.proargtypes::oid[]) with ordinality as a(t, i)
               join pg_type ty on ty.oid = a.t order by a.i) as argtypnames,
         p.pronargdefaults as ndefaults,
         format_type(p.prorettype, null) as ret, rt.typname as rettypname, p.proretset as retset
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
  join pg_type rt on rt.oid = p.prorettype
  where p.prokind = 'f' and rt.typname <> 'trigger'
  order by p.proname
""")

SCALAR = {
    "uuid": "string", "text": "string", "citext": "string", "varchar": "string", "bpchar": "string",
    "inet": "unknown", "date": "string", "timestamptz": "string", "timestamp": "string", "time": "string",
    "int2": "number", "int4": "number", "int8": "number", "float4": "number", "float8": "number",
    "numeric": "number", "bool": "boolean", "json": "Json", "jsonb": "Json", "bytea": "string",
    "void": "undefined",
}


def ts_type(typname: str, elem: str | None = None) -> str:
    if elem:
        return f"{ts_type(elem)}[]"
    if typname.startswith("_"):
        return f"{ts_type(typname[1:])}[]"
    if typname in enum_names:
        return f'Database["public"]["Enums"]["{typname}"]'
    if typname == "inet":
        return "string"
    return SCALAR.get(typname, "unknown")


rels: dict[str, dict] = {}
for c in cols:
    r = rels.setdefault(c["rel"], {"kind": c["kind"], "cols": []})
    r["cols"].append(c)

out: list[str] = []
w = out.append
w("// AUTO-GENERATED by supabase/scripts/gen_types.py from the migrations in supabase/migrations.")
w("// Same shape as `supabase gen types typescript`; regenerate after every schema change:")
w("//   supabase gen types typescript --local > web/src/lib/db.types.ts   (when Docker is available)")
w("//   or: supabase/tests/local/run.sh && python3 supabase/scripts/gen_types.py beacon_validate web/src/lib/db.types.ts")
w("")
w("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]")
w("")
w("export type Database = {")
w("  public: {")


def rel_block(name: str, r: dict, editable: bool):
    w(f"      {name}: {{")
    w("        Row: {")
    for c in r["cols"]:
        t = ts_type(c["typname"], c["elemtype"])
        nullable = c["nullable"] or r["kind"] != "r"
        w(f"          {c['col']}: {t}{' | null' if nullable else ''}")
    w("        }")
    if editable:
        for section in ("Insert", "Update"):
            w(f"        {section}: {{")
            for c in r["cols"]:
                t = ts_type(c["typname"], c["elemtype"])
                if c["is_generated"]:
                    w(f"          {c['col']}?: never")
                    continue
                optional = section == "Update" or c["nullable"] or c["has_default"] or c["is_identity"]
                w(f"          {c['col']}{'?' if optional else ''}: {t}{' | null' if c['nullable'] else ''}")
            w("        }")
    w("        Relationships: [")
    for fk in [f for f in fks if f["rel"] == name]:
        w("          {")
        w(f'            foreignKeyName: "{fk["name"]}"')
        w(f"            columns: {json.dumps(fk['columns'])}")
        w(f"            isOneToOne: {'true' if fk['one_to_one'] else 'false'}")
        w(f'            referencedRelation: "{fk["ref"]}"')
        w(f"            referencedColumns: {json.dumps(fk['ref_columns'])}")
        w("          },")
    w("        ]")
    w("      }")


w("    Tables: {")
for name, r in sorted(rels.items()):
    if r["kind"] == "r":
        rel_block(name, r, True)
w("    }")
w("    Views: {")
for name, r in sorted(rels.items()):
    if r["kind"] in ("v", "m"):
        rel_block(name, r, False)
w("    }")
w("    Functions: {")
seen = set()
for f in funcs:
    if f["name"] in seen:
        continue
    seen.add(f["name"])
    w(f"      {f['name']}: {{")
    n = len(f["argtypnames"])
    if n == 0:
        w("        Args: never")
    else:
        w("        Args: {")
        first_default = n - f["ndefaults"]
        for i, (an, at) in enumerate(zip(f["argnames"], f["argtypnames"])):
            w(f"          {an}{'?' if i >= first_default else ''}: {ts_type(at)}")
        w("        }")
    ret = ts_type(f["rettypname"])
    w(f"        Returns: {ret}{'[]' if f['retset'] else ''}")
    w("      }")
w("    }")
w("    Enums: {")
for e in enums:
    w(f"      {e['name']}: {' | '.join(json.dumps(l) for l in e['labels'])}")
w("    }")
w("    CompositeTypes: {")
w("      [_ in never]: never")
w("    }")
w("  }")
w("}")
w("")
w('type PublicSchema = Database["public"]')
w("")
w('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]')
w('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]')
w('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]')
w('export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"]')
w('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]')
w("")
w("export const Constants = {")
w("  public: {")
w("    Enums: {")
for e in enums:
    w(f"      {e['name']}: {json.dumps(e['labels'])},")
w("    },")
w("  },")
w("} as const")
w("")

with open(OUT, "w") as fh:
    fh.write("\n".join(out))
print(f"wrote {OUT}: {sum(1 for r in rels.values() if r['kind']=='r')} tables, "
      f"{sum(1 for r in rels.values() if r['kind']!='r')} views, {len(seen)} functions, {len(enums)} enums")
